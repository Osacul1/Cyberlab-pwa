// Teste do mecanismo real de backup em armazenamento simulado; não altera dados do usuário.
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const core=html.slice(html.indexOf('const L=(phase'),html.indexOf('const defaultState='));
const lessons=JSON.parse(vm.runInNewContext(core+'\nJSON.stringify(lessons)'));
const from=html.indexOf('const KEYS=['),to=html.indexOf('// Programação: a atividade',from);
assert(from>0&&to>from,'Rotinas de backup não encontradas');
const storage=new Map(),alerts=[];let captured='',reloaded=0;
const localStorage={getItem:k=>storage.has(k)?storage.get(k):null,setItem:(k,v)=>storage.set(k,String(v)),removeItem:k=>storage.delete(k)};
const doc={body:{append(){},},createElement:()=>({click(){},remove(){},set href(v){},set download(v){}})};
class Reader{readAsText(file){this.result=file.text;if(this.onload)this.onload()}}
const ctx={window:{},lessons,devLAll:[],labC:[],localStorage,document:doc,FileReader:Reader,Blob:class{constructor(data){captured=data.join('')}},URL:{createObjectURL:()=>'/backup',revokeObjectURL(){}},setTimeout:()=>0,toast:()=>{},alert:m=>alerts.push(m),confirm:()=>true,location:{reload:()=>reloaded++}};
vm.runInNewContext('(function(){"use strict";'+html.slice(from,to)+'})();',ctx);
const original={completed:[0,4,138],xp:150,notes:'teste',wordsLearned:[]};
localStorage.setItem('cyberlab_v2',JSON.stringify(original));
localStorage.setItem('cyberlab_method_v1',JSON.stringify({'english:a0-1':{attempts:1,streak:1,due:Date.now()+86400000,last:Date.now(),accuracy:1}}));
localStorage.setItem('cyberlab_projects_v1',JSON.stringify({'0':{note:'Um exemplo fictício bem explicado para testar persistência.',checks:[true,true,true,true],completed:true}}));
localStorage.setItem('cyberlab_simlab_v1',JSON.stringify({completed:['terminal','sql']}));
ctx.window.exportData();
const backup=JSON.parse(captured);
assert.equal(backup.version,9);
assert.equal(backup.catalog.cybersecurity.length,139);
assert.equal(backup.storage.cyberlab_v2.completed.length,3);
assert.equal(backup.storage.cyberlab_method_v1['english:a0-1'].streak,1);
assert.equal(backup.storage.cyberlab_projects_v1['0'].completed,true);
assert.equal(backup.storage.cyberlab_simlab_v1.completed.length,2);
localStorage.setItem('cyberlab_v2',JSON.stringify({...original,completed:[],xp:0}));
ctx.window.importData({target:{files:[{size:captured.length,text:captured}],value:'backup'}});
assert.deepEqual(JSON.parse(localStorage.getItem('cyberlab_v2')).completed,original.completed);
assert.equal(reloaded,1);
const reordered=JSON.parse(captured);
[reordered.catalog.cybersecurity[0],reordered.catalog.cybersecurity[4]]=[reordered.catalog.cybersecurity[4],reordered.catalog.cybersecurity[0]];
reordered.storage.cyberlab_v2.completed=[0];
const reorderedText=JSON.stringify(reordered);
ctx.window.importData({target:{files:[{size:reorderedText.length,text:reorderedText}],value:'backup'}});
assert.deepEqual(JSON.parse(localStorage.getItem('cyberlab_v2')).completed,[4],'IDs devem mapear o progresso após reordenação');
const before=localStorage.getItem('cyberlab_v2');
const invalid=JSON.stringify({...backup,catalog:{cybersecurity:['inexistente']}});
ctx.window.importData({target:{files:[{size:invalid.length,text:invalid}],value:'backup'}});
assert.equal(localStorage.getItem('cyberlab_v2'),before,'Backup inválido não deve substituir dados');
assert(alerts.some(x=>x.includes('não foram encontradas')),'Erro de catálogo não reportado');
console.log('APROVADO: exportação, restauração, remapeamento por ID e rejeição de backup incompatível.');
